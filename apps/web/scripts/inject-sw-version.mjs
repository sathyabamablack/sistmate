#!/usr/bin/env node
/**
 * Runs before `next build` (npm "prebuild"). Picks one id for this build and
 * writes it where the app needs it:
 *
 *   public/sw-version.js  -> sets self.__USP_BUILD__ for the service worker, which puts it
 *                            in its cache names so each deploy refreshes the offline page
 *   .build-id             -> read by next.config.mjs (NEXT_PUBLIC_BUILD_ID, Next's build id)
 *
 * Both files are generated and gitignored. The id is the git commit when there is one,
 * otherwise a timestamp, so it is the same for every process within one build.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function gitShortSha() {
  try {
    return execSync("git rev-parse --short=8 HEAD", { stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return "";
  }
}

const fromEnv =
  process.env.BUILD_ID ||
  process.env.VERCEL_GIT_COMMIT_SHA ||
  process.env.GITHUB_SHA ||
  process.env.SOURCE_VERSION ||
  "";

// Uncommitted edits would keep the same commit id; add the time so a local rebuild still updates.
const base = (fromEnv.slice(0, 8) || gitShortSha() || "local").replace(/[^a-zA-Z0-9]/g, "");
const id = fromEnv ? base : `${base}-${Date.now().toString(36)}`;

// The asset host (see ASSET_PREFIX in next.config.mjs), so the worker also caches files from there.
const assetOrigin = process.env.ASSET_PREFIX ? new URL(process.env.ASSET_PREFIX).origin : "";

mkdirSync(join(root, "public"), { recursive: true });
writeFileSync(
  join(root, "public", "sw-version.js"),
  `// Generated by scripts/inject-sw-version.mjs at build time. Do not edit or commit.\nself.__USP_BUILD__ = ${JSON.stringify(id)};\nself.__USP_ASSETS__ = ${JSON.stringify(assetOrigin)};\n`,
);
writeFileSync(join(root, ".build-id"), `${id}\n`);

console.log(`[build] build id ${id}`);
